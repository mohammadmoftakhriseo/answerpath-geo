<script>
document.addEventListener('DOMContentLoaded', function () {
    const faqContainer = document.getElementById('custom-dev-faq-accordion');
    if (!faqContainer) return;

    const toggles = faqContainer.querySelectorAll('.faq-toggle');
    toggles.forEach(toggle => {
        toggle.addEventListener('click', function () {
            const item = this.closest('.faq-item');
            const answer = item.querySelector('.faq-answer');
            const icon = this.querySelector('i');
            const isExpanded = this.getAttribute('aria-expanded') === 'true';

            // بستن سایر آیتم‌ها
            toggles.forEach(otherToggle => {
                if (otherToggle !== this) {
                    otherToggle.setAttribute('aria-expanded', 'false');
                    const otherItem = otherToggle.closest('.faq-item');
                    otherItem.querySelector('.faq-answer').classList.add('hidden');
                    const otherIcon = otherToggle.querySelector('i');
                    otherIcon.classList.remove('rotate-180', 'text-accent', 'dark:text-blue-400');
                }
            });

            // تغییر وضعیت آیتم جاری
            if (isExpanded) {
                this.setAttribute('aria-expanded', 'false');
                answer.classList.add('hidden');
                icon.classList.remove('rotate-180', 'text-accent', 'dark:text-blue-400');
            } else {
                this.setAttribute('aria-expanded', 'true');
                answer.classList.remove('hidden');
                icon.classList.add('rotate-180', 'text-accent', 'dark:text-blue-400');
            }
        });
    });
});
</script>
